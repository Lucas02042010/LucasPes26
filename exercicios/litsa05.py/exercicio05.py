def maior_valor(lista):
    if len(lista):
        return -1
    else:
        return max(lista)

def menor_valor(lista):
    if len(lista):
        return -1
    else:
        return min(lista)
        
def medio_valor(lista):
    if len(lista):
        return -1
    else:
        return sum(lista) / len(lista)
    

